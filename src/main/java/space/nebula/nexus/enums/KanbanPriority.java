package space.nebula.nexus.enums;

public enum KanbanPriority {
	/**
	 * Indicates a task with low priority; can be deferred without significant
	 * impact.
	 */
	LOW,

	/**
	 * Indicates a task with medium priority; should be addressed in due course.
	 */
	MEDIUM,

	/**
	 * Indicates a task with high priority; requires immediate attention.
	 */
	HIGH
}